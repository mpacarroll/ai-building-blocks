def _criteria_by_req(spec):
    out = {}
    for ac in spec["acceptance"]:
        out.setdefault(ac.get("requirement"), []).append(ac)
    return out


def _ac_line(ac):
    return f"Given {ac['given']}, when {ac['when']}, then {ac['then']}"


def to_markdown(spec: dict, rev: int = None) -> str:
    L = [f"# {spec['title']}", ""]
    if rev:
        L += [f"Revision {rev}. Generated by spec-bench from spec.json; edit the workspace, "
              "not this file.", ""]
    L += ["## Problem", "", spec["problem"] or "(not stated yet)", ""]
    for coll in ("users", "goals", "non_goals", "constraints"):
        L += [f"## {model.COLLECTIONS[coll][1]}", ""]
        L += [f"- {i['id']}: {i['text']}" for i in spec[coll]] or ["(none yet)"]
        L.append("")
    L += ["## Requirements", ""]
    by_req = _criteria_by_req(spec)
    if not spec["requirements"]:
        L.append("(none yet)")
    for n, r in enumerate(spec["requirements"], start=1):
        dep = f" Depends on {', '.join(r['depends_on'])}." if r.get("depends_on") else ""
        L.append(f"{n}. **{r['id']}** ({r['priority']}) {r['text']}{dep}")
        for ac in by_req.get(r["id"], []):
            L.append(f"   - {ac['id']} ({ac['status']}): {_ac_line(ac)}")
    L.append("")
    L += ["## Decisions", ""]
    for d in spec["decisions"]:
        if d["status"] == "decided":
            why = f" Rationale: {d['rationale']}" if d.get("rationale") else ""
            L.append(f"- {d['id']} (decided): {d['question']} Choice: {d['choice']}.{why}")
        else:
            opts = f" Options: {' / '.join(d['options'])}." if d.get("options") else ""
            L.append(f"- {d['id']} (open): {d['question']}{opts}")
    if not spec["decisions"]:
        L.append("(none yet)")
    L += ["", "## Assumptions", ""]
    for a in spec["assumptions"]:
        v = f" Validation: {a['validation']}" if a.get("validation") else " Validation: none yet."
        L.append(f"- {a['id']}: {a['text']}{v}")
    if not spec["assumptions"]:
        L.append("(none yet)")
    if spec["unclassified"]:
        L += ["", "## Unclassified intake (review these)", ""]
        L += [f"- {x['id']} (line {x.get('source', {}).get('line', '?')}): {x['text']}"
              for x in spec["unclassified"]]
    return "\n".join(L) + "\n"


def to_json(spec: dict) -> str:
    return json.dumps(spec, indent=2, ensure_ascii=False) + "\n"


def lint(spec: dict) -> dict:
    """Spec Grader's wording score of the exported markdown."""
    return _grade.grade(to_markdown(spec))


def to_checklist(spec: dict, rev: int = None) -> str:
    by_req = _criteria_by_req(spec)
    L = [f"# Test checklist: {spec['title']}", ""]
    if rev:
        L += [f"From revision {rev}.", ""]
    L += ["Tick an item only after you have watched the behavior happen. A ticked box "
          "is a claim, not proof; link the test or recording next to it.", "",
          "## Acceptance criteria", ""]
    gaps = []
    for r in spec["requirements"]:
        acs = by_req.get(r["id"], [])
        if not acs:
            gaps.append(r)
            continue
        L.append(f"### {r['id']} ({r['priority']}): {r['text']}")
        for ac in acs:
            L.append(f"- [ ] {ac['id']}: {_ac_line(ac)}")
        L.append("")
    if gaps:
        L += ["## Requirements with no criterion (not testable yet)", ""]
        L += [f"- [ ] {r['id']} ({r['priority']}): {r['text']}" for r in gaps]
        L.append("")
    open_d = [d for d in spec["decisions"] if d["status"] != "decided"]
    if open_d:
        L += ["## Open decisions (resolve before building)", ""]
        L += [f"- [ ] {d['id']}: {d['question']}" for d in open_d]
        L.append("")
    if spec["assumptions"]:
        L += ["## Assumptions to validate", ""]
        L += [f"- [ ] {a['id']}: {a['text']} ({a.get('validation') or 'no plan yet'})"
              for a in spec["assumptions"]]
        L.append("")
    return "\n".join(L)


def _slug(text, n=6):
    return "_".join(re.findall(r"[a-z0-9]+", text.lower())[:n]) or "item"


def _doc(text):
    return text.replace("\\", "\\\\").replace('"""', '\\"\\"\\"')


def to_pytest(spec: dict, rev: int = None) -> str:
    reqs = {r["id"]: r for r in spec["requirements"]}
    L = [f'"""Acceptance tests for: {_doc(spec["title"])}'
         + (f" (revision {rev})" if rev else ""), "",
         "Generated by spec-bench. Every test raises NotImplementedError until a person",
         "writes the real check, so an untouched skeleton fails instead of passing.",
         '"""', "", ""]
    for ac in spec["acceptance"]:
        r = reqs.get(ac.get("requirement"), {"id": ac.get("requirement"), "text": "(missing)"})
        name = f"test_{ac['id'].lower()}_{_slug(r['text'])}"
        L += [f"def {name}():",
              f'    """{_doc(str(r["id"]))}: {_doc(r["text"])}', "",
              f"    Given {_doc(ac['given'])}",
              f"    When {_doc(ac['when'])}",
              f"    Then {_doc(ac['then'])}",
              '    """',
              f'    raise NotImplementedError("write the check for {ac["id"]}")', "", ""]
    gaps = [r for r in spec["requirements"] if r["id"] not in _criteria_by_req(spec)]
    if gaps:
        L.append("# Requirements with no acceptance criterion, so no test was generated:")
        L += [f"#   {r['id']}: {r['text']}" for r in gaps]
    return "\n".join(L).rstrip() + "\n"


