def _e(s):
    return _html.escape(str(s if s is not None else ""))


def to_html(spec: dict, rev: int = None, history: list = None) -> str:
    findings = checks.run(spec)
    s = checks.summary(findings)
    lint_result = lint(spec)
    if s["ready"]:
        banner = "<p class='banner ready'>Ready to build: no blocking findings.</p>"
    else:
        banner = (f"<p class='banner notready'>Not ready to build: {s['blocking']} blocking "
                  "finding(s).</p>")
    chips = "".join(f"<span class='chip'>{_e(v)} {k}</span>"
                    for k, v in s.items() if k != "ready")
    items = []
    for f in findings:
        tag = " judgment call" if f["judgment"] else ""
        waived = (f"<div class='fix'>Waived: {_e(f['waiver'])}</div>" if f["waived"] else "")
        cls = f"finding {f['severity']}" + (" waived" if f["waived"] else "")
        items.append(
            f"<div class='{cls}'><span class='sev-{f['severity']}'>{_e(f['severity'])}</span> "
            f"<code>{_e(f['rule'])}</code> {_e(f['name'])}<span class='muted'>{tag}</span>"
            f"<div>{_e(f['message'])}</div><div class='fix'>Fix: {_e(f['fix'])}</div>"
            f"{waived}<div class='fix'>Key: <code>{_e(f['key'])}</code></div></div>")
    hist = ""
    if history:
        rows = "".join(f"<tr><td>{_e(h['rev'])}</td><td>{_e(h['at'])}</td>"
                       f"<td>{_e(h['message'])}</td></tr>" for h in history)
        hist = ("<h2>Revision history</h2><table><tr><th>Rev</th><th>When</th>"
                f"<th>Message</th></tr>{rows}</table>")
    limits = "".join(f"<li>{_e(x)}</li>" for x in checks.LIMITS)
    title = _e(spec["title"])
    revtxt = f" (revision {_e(rev)})" if rev else ""
    return f"""<!doctype html><html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Spec workbench report</title><style>{_CSS}</style></head><body><main>
<p class="muted">Spec workbench report{revtxt}</p>
<h1>{title}</h1>
<div class="card">{banner}<div class="counts">{chips}</div>
<p>Wording lint (Spec Grader): <b>{_e(lint_result['grade'])}</b>
({_e(lint_result['score'])}/100). {_e(checks.GRADE_DISCLAIMER)}</p></div>
<h2>Findings</h2>{''.join(items) or '<p>No findings.</p>'}
<h2>What these checks cannot judge</h2><ul>{limits}</ul>
<h2>Spec</h2><pre>{_e(to_markdown(spec, rev))}</pre>
<h2>Test checklist</h2><pre>{_e(to_checklist(spec, rev))}</pre>
{hist}
</main></body></html>
"""


FORMATS = {"md": to_markdown, "checklist": to_checklist, "pytest": to_pytest}
